     * Автоматическое создание категорий, товаров и должностей для организации
     */
    public static function setupOrganization(int $orgId, string $businessType, ?int $userId = null): array {
        $pdo = Database::getConnection();
        $preset = self::getPresets($businessType);

        $createdCategories = [];
        $createdItemsCount = 0;
        $createdPositionsCount = 0;

        // 1. Создаем категории
        foreach ($preset['categories'] as $index => $catName) {
            $stmt = $pdo->prepare("
                INSERT INTO menu_categories (organization_id, user_id, name, sort_order) 
                VALUES (?, ?, ?, ?)
            ");
            $stmt->execute([$orgId, $userId, $catName, $index * 10]);
            $createdCategories[$index] = (int)$pdo->lastInsertId();
        }

        // 2. Создаем позиции каталога / меню
        foreach ($preset['items'] as $item) {
            $catId = $createdCategories[$item['cat']] ?? null;
            $stmt = $pdo->prepare("
                INSERT INTO menu_items (organization_id, user_id, category_id, name, description, price, unit, is_active)
                VALUES (?, ?, ?, ?, ?, ?, ?, 1)
            ");
            $stmt->execute([
                $orgId,
                $userId,
                $catId,
                $item['name'],
                $item['desc'] ?? '',
                $item['price'],
                $item['unit'] ?? 'шт'
            ]);
            $createdItemsCount++;
        }

        // 3. Создаем должности
        foreach ($preset['positions'] as $pos) {
            $stmt = $pdo->prepare("
                INSERT INTO positions (organization_id, user_id, name, department, description, salary_min, salary_max, is_active)
                VALUES (?, ?, ?, ?, ?, ?, ?, 1)
            ");
            $stmt->execute([
                $orgId,
                $userId,
                $pos['name'],
                $pos['dept'] ?? 'Отдел',
                $pos['desc'] ?? '',
                $pos['salary_min'] ?? null,
                $pos['salary_max'] ?? null
            ]);
            $createdPositionsCount++;
        }

        return [
            'categories' => count($createdCategories),
            'items'      => $createdItemsCount,
            'positions'  => $createdPositionsCount
        ];
    }
